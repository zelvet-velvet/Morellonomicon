"""Write Review/Tag Audit.md: for every ability tag (控場, 強化普攻 ...), each champion skill that got it and the words that matched.

The tags come from regular expressions over Riot's skill text (FEATURES in fetch_data.py). The full tooltips they read are
not stored in the notes, so this file is how a person (or an LLM) checks a rule: a snippet that does not mean the tag is a
rule to narrow. Reads the same Data Dragon files as fetch_data.py (cached in .cache/ddragon). Standard library only.

    python3 -I tools/audit_tags.py
"""
import json
import re
import sys
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))   # python3 -I does not add the script folder
import fetch_data  # noqa: E402

OUT = fetch_data.ROOT / "Review" / "Tag Audit.md"
AROUND = 14   # characters shown on each side of a match


def plain(text):
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", text or "")).strip()


def snippet(text, m):
    a, b = max(0, m.start() - AROUND), min(len(text), m.end() + AROUND)
    return ("…" if a else "") + text[a:m.start()] + "**" + m.group(0) + "**" + text[m.end():b] + ("…" if b < len(text) else "")


def main():
    version = json.loads(urllib.request.urlopen(f"{fetch_data.DD}/api/versions.json", timeout=30).read())[0]
    loc = fetch_data.LOCALE
    listing = fetch_data.fetch(f"{fetch_data.DD}/cdn/{version}/data/{loc}/champion.json", f"{version}/champion.json")["data"]

    def one(cid):
        return fetch_data.fetch(f"{fetch_data.DD}/cdn/{version}/data/{loc}/champion/{cid}.json", f"{version}/champion/{cid}.json")["data"][cid]

    with ThreadPoolExecutor(fetch_data.WORKERS) as pool:
        champions = sorted(pool.map(one, listing), key=lambda c: c["id"])
    hits = {tag: [] for tag in fetch_data.FEATURES}
    for c in champions:
        skills = [("P", c["passive"])] + list(zip("QWER", c["spells"]))
        for key, s in skills:
            # the tagged text, the way skill_tags reads it, but without the markup the regexes never need
            text = plain(s.get("description", "")) + " ‖ " + plain(s.get("tooltip", ""))
            raw = s.get("description", "") + s.get("tooltip", "")
            for tag in fetch_data.FEATURES:
                hit = fetch_data.tag_search(tag, raw)
                if not hit:
                    continue
                m = fetch_data.tag_search(tag, text)
                shown = snippet(text, m) if m else "(matched only inside markup: " + hit.group(0) + ")"
                hits[tag].append(f"| {c['name']} | {key} {s['name']} | {shown.replace('|', '/')} |")
    lines = ["# Tag Audit", "",
             f"Generated by `tools/audit_tags.py` for patch {version}: every skill each ability tag was given, with the words that matched "
             "(‖ separates the short description from the full tooltip). Use it to narrow a rule in FEATURES (`tools/fetch_data.py`). "
             "Hand-set tags (`features_extra`, `onhit`) are not listed.", ""]
    for tag, rows in hits.items():
        champs = len({r.split(" | ")[0] for r in rows})
        lines += [f"## {tag} ({champs} champions, {len(rows)} skills)", "", f"Rule: `{fetch_data.FEATURES[tag]}`", ""] + ([f"Ignored: `{fetch_data.NOT_FEATURES[tag]}`", ""] if tag in fetch_data.NOT_FEATURES else []) + [
                  "| Champion | Skill | Matched |", "| --- | --- | --- |"] + rows + [""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(fetch_data.ROOT)}: " + ", ".join(f"{t} {len(r)}" for t, r in hits.items()))


if __name__ == "__main__":
    main()
