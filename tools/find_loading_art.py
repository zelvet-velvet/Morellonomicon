"""List the game's loading screen and ARAM map pictures on CommunityDragon into Review/Loading Art.md, to pick the backgrounds
for the Handbook's loading tip card. Only addresses are written (pictures are never stored in the repo).

CommunityDragon serves a JSON listing of every folder (raw.communitydragon.org/json/...). This walks a few folders where
loading screen and map art live and keeps the image files whose path names a loading screen or an ARAM map.
Standard library only.

    python3 -I tools/find_loading_art.py
"""
import json
import re
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "Review" / "Loading Art.md"
LIST = "https://raw.communitydragon.org/json/latest/"
RAW = "https://raw.communitydragon.org/latest/"
USER_AGENT = "Morellonomicon/0.1 (+https://github.com/zelvet-velvet/Morellonomicon)"
START = ["game/assets/loadingscreen/", "plugins/rcp-fe-lol-loading-screen/global/default/", "game/assets/maps/", "plugins/rcp-be-lol-game-data/global/default/content/src/leagueclient/gamemodeassets/"]
WANTED = re.compile(r"loading|map12|aram|howling|abyss|bridge|butcher|bilgewater|progress|koeshin|kiwi", re.I)
IMAGE = re.compile(r"\.(png|jpe?g|webp)$", re.I)
MAX_DEPTH, MAX_DIRS = 5, 400


def listing(path):
    req = urllib.request.Request(LIST + path, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


def main():
    found, seen, queue = [], 0, [(p, 0) for p in START]
    while queue and seen < MAX_DIRS:
        path, depth = queue.pop(0)
        try:
            items = listing(path)
        except Exception as e:   # a folder that is not there in this patch
            print(f"! {path}: {e}", file=sys.stderr)
            continue
        seen += 1
        for it in items:
            name = it.get("name", "")
            full = path + name
            if it.get("type") == "directory":
                # under the maps folder only follow folders that name an ARAM map; elsewhere follow everything
                if depth < MAX_DEPTH and (not path.startswith("game/assets/maps/") or WANTED.search(full)):
                    queue.append((full + "/", depth + 1))
            elif IMAGE.search(name) and WANTED.search(full):
                found.append((full, it.get("size", 0)))
    lines = ["# Loading Art", "", f"Generated by `tools/find_loading_art.py`: image files on CommunityDragon whose path names a loading screen or an ARAM map "
             f"({len(found)} files, {seen} folders looked at). Biggest first; open an address to see it.", "", "| Size (KB) | Address |", "| --- | --- |"]
    lines += [f"| {size // 1024} | {RAW}{p} |" for p, size in sorted(found, key=lambda x: -x[1])[:300]]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(found)} pictures from {seen} folders")


if __name__ == "__main__":
    main()
